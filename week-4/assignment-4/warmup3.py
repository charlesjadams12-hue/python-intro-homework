languages = {"Python", "C", "Rust", "HTML", "CSS"}
other_languages = {"C++", "HTML", "CSS", "JavaScript", "SQL"}
# Prints the union of both sets.
print(languages.union(other_languages))
# Prints the intersection of the both sets.
print(languages.intersection(other_languages))
# Outputs the difference between both sets
print(languages.difference(other_languages))